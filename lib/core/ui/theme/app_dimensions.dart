/// Константы размеров, отступов и метрик для всего приложения.
/// Централизует логические размеры (dp), используемые в дизайне,
/// чтобы избежать хардкода значений по всему проекту.
class AppDimensions {
  // Защита от создания экземпляра утилитного класса
  AppDimensions._();

  /// Минимальный безопасный отступ сверху для экрана (например, для выреза камеры).
  /// Равен 40.0 dp, что оптимально для Tecno Pova 5 (Dot-in-Display).
  static const double minTopSafePadding = 40.0;

  /// Минимальный безопасный отступ снизу (например, для системной навигации).
  /// Равен 48.0 dp, чтобы контент не перекрывался подбородком.
  static const double minBottomSafePadding = 0.0;

  /// Базовая ширина логического экрана, на которую ориентирован дизайн.
  static const double logicalWidth = 360.0;

  /// Базовая высота логического экрана, на которую ориентирован дизайн.
  static const double logicalHeight = 820.0;
}
